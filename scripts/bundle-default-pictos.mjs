#!/usr/bin/env node
/**
 * Downloads the ARASAAC pictograms used by the default boards into
 * assets/pictos/ and generates src/data/default-pictos.ts, so the starter
 * vocabulary works offline from the very first launch.
 *
 * Run after changing src/data/default-boards.ts:
 *   npm run pictos:bundle
 *
 * Pictograms: Sergio Palao, property of the Government of Aragón, ARASAAC
 * (https://arasaac.org), CC BY-NC-SA 4.0.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const boardsSource = readFileSync(join(root, 'src/data/default-boards.ts'), 'utf8');

// word('id', 'label', 1234) / folder('id', 'label', 1234, 'target'): the picto id is the 3rd argument.
const ids = [
  ...new Set(
    [...boardsSource.matchAll(/(?:word|folder)\(\s*'[^']*',\s*(?:'[^']*'|"[^"]*"),\s*(\d+)/g)].map((m) => Number(m[1])),
  ),
].sort((a, b) => a - b);
if (ids.length === 0) throw new Error('No pictogram ids found in default-boards.ts');

const outDir = join(root, 'assets/pictos');
mkdirSync(outDir, { recursive: true });

for (const id of ids) {
  const res = await fetch(`https://static.arasaac.org/pictograms/${id}/${id}_300.png`);
  if (!res.ok) throw new Error(`Picto ${id}: HTTP ${res.status}`);
  writeFileSync(join(outDir, `${id}.png`), Buffer.from(await res.arrayBuffer()));
  process.stdout.write('.');
}

const lines = ids.map((id) => `  ${id}: require('../../assets/pictos/${id}.png'),`);
writeFileSync(
  join(root, 'src/data/default-pictos.ts'),
  `// Generated by scripts/bundle-default-pictos.mjs. Do not edit by hand.
// ARASAAC pictograms (Sergio Palao, Government of Aragón), CC BY-NC-SA 4.0.

/** Pictograms bundled with the app, by ARASAAC id: available offline from the first launch. */
export const BUNDLED_PICTOS: Record<number, number> = {
${lines.join('\n')}
};
`,
);
console.log(`\n${ids.length} pictograms bundled.`);
